-- Разные главы одной книги теперь можно озвучивать разными голосами
-- одного владельца (выбор голоса стал per-chapter в UI) — ссылка на пару
-- (книга, голос) из миграции 0019 для этого не годится: показала бы
-- только главы ОДНОГО голоса, остальные выглядели бы неозвученными.
-- Меняем на (книга, владелец) — безопасно (все голоса владельца — его
-- собственные, кросс-пользовательской утечки, из-за которой убирали
-- books.share_token в 0019, здесь нет), и поддерживает микс голосов
-- по главам в рамках одного пользователя.
alter table public.book_share_links drop column voice_id;
alter table public.book_share_links add constraint book_share_links_book_id_owner_id_key unique (book_id, owner_id);
