create table public.story_templates (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  language text not null default 'ru',
  text_plain text not null,
  text_marked text not null,
  created_at timestamptz not null default now()
);

alter table public.story_templates enable row level security;

create policy "story_templates: authenticated can read"
  on public.story_templates for select
  to authenticated
  using (true);

alter table public.stories add column if not exists template_id uuid references public.story_templates(id);

